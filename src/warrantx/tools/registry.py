"""Tool registry and execution adapters for Google ADK agents.

Implements T057 (FR-CHAT-03, FR-TOOL-*):
- Provides static status-text mapping for each tool (never generated by LLM).
- Sanitizes and validates tool arguments (identifiers and numbers only, no URLs).
- Automatically wraps tool outputs into Evidence records.
"""

from __future__ import annotations

from typing import Any, Callable
from warrantx.data.repo import AsyncRepository
from warrantx.tools.evidence import Evidence
from warrantx.tools.warrants import build_warrant_card
from warrantx.tools.entity import resolve_entity


# Static status-text map (emitted during SSE streaming, FR-CHAT-03)
TOOL_STATUS_MAP: dict[str, str] = {
    "get_warrant_card": "Fetching warrant quotes and recomputing risk metrics...",
    "search_warrants": "Scanning Bursa Malaysia structured warrant board...",
    "run_scenario": "Simulating Black-Scholes scenario trajectory...",
    "compare_warrants": "Comparing warrant terms and holding friction...",
    "resolve_underlying": "Resolving stock name and Bursa ticker code...",
    "get_news": "Fetching verified 7-day news recency window...",
    "explain_move": "Decomposing warrant price move sequentially...",
}


def get_tool_status_text(tool_name: str) -> str:
    """Retrieve human-friendly static status text for a tool execution."""
    return TOOL_STATUS_MAP.get(tool_name, f"Executing {tool_name}...")


class ToolRegistry:
    """Central registry of analytical tools available to the Root Agent."""

    def __init__(self, repo: AsyncRepository, news_service: Any = None) -> None:
        self.repo = repo
        self.news_service = news_service

    async def get_warrant_card(
        self,
        code: str,
        holding_days: int = 5,
        turn_id: str = "",
        evidence_index: int = 1,
    ) -> tuple[dict[str, Any], Evidence | None]:
        """Fetch quote row, compute metrics, and return full card + evidence."""
        snapshot = await self.repo.get_latest_good_snapshot()
        if not snapshot:
            return {"error": "no_snapshot_available"}, None

        row = await self.repo.get_warrant(code.strip().upper(), snapshot_id=snapshot.id)
        if not row:
            return {"error": f"Warrant code '{code}' not found"}, None

        ev_id = f"E{evidence_index}"
        card, evidence = build_warrant_card(
            row=row,
            holding_days=holding_days,
            as_of=snapshot.fetched_at.isoformat(),
            mode="replay",
            evidence_id=ev_id,
        )

        # Set turn_id on evidence if provided
        if turn_id:
            evidence.turn_id = turn_id
            await self.repo.save_evidence(
                turn_id=turn_id,
                evidence_id=ev_id,
                kind="card",
                source=f"warrant_card_{code}",
                payload_json=card.model_dump(),
            )

        return card.model_dump(), evidence

    async def resolve_underlying(
        self,
        query: str,
    ) -> dict[str, Any]:
        """Resolve company name to Bursa ticker."""
        underlyings = await self.repo.get_underlyings()
        candidates = [
            {"ticker": u.ticker, "code": u.code, "name": u.name}
            for u in underlyings
        ]
        result = resolve_entity(query, candidates=candidates)
        return result.model_dump()

    async def run_scenario(
        self,
        code: str,
        move: float,
        days: int = 0,
        iv_shift: float = 0.0,
        turn_id: str = "",
        evidence_index: int = 2,
    ) -> tuple[dict[str, Any], Evidence | None]:
        """Simulate what-if trajectory across underlying move, holding time, and IV shift."""
        from warrantx.tools.scenario import execute_scenario

        ev_id = f"E{evidence_index}"
        res, evidence = await execute_scenario(
            repo=self.repo,
            code=code,
            move=move,
            days=days,
            iv_shift=iv_shift,
            turn_id=turn_id,
            evidence_id=ev_id,
        )
        return res.model_dump(), evidence

    async def search_news(
        self,
        ticker: str,
        query: str | None = None,
        turn_id: str = "",
        evidence_index: int = 1,
    ) -> tuple[dict[str, Any], Evidence]:
        """Fetch 7-day recency news context for ticker wrapped into Evidence."""
        from warrantx.tools.news import search_news as execute_search_news

        return await execute_search_news(
            ticker=ticker,
            query=query,
            service=self.news_service,
            repo=self.repo,
            turn_id=turn_id,
            evidence_index=evidence_index,
        )

    async def compare_warrants(
        self,
        codes: list[str],
        holding_days: int = 5,
        turn_id: str = "",
        evidence_index: int = 1,
    ) -> tuple[dict[str, Any], Evidence]:
        """Compare 2 to 3 warrants uniformly on the same underlying stock."""
        from warrantx.tools.compare import compare_warrants as execute_compare

        return await execute_compare(
            codes=codes,
            repo=self.repo,
            holding_days=holding_days,
            turn_id=turn_id,
            evidence_index=evidence_index,
        )

    async def get_stock_summary(
        self,
        ticker: str,
        holding_days: int = 5,
        turn_id: str = "",
        evidence_index: int = 1,
    ) -> tuple[dict[str, Any], Evidence]:
        """Fetch stock-level warrant overview with medians and nearest warrants."""
        from warrantx.tools.stock import get_stock_summary as execute_stock_summary

        res, ev = await execute_stock_summary(
            ticker=ticker,
            repo=self.repo,
            holding_days=holding_days,
            turn_id=turn_id,
            evidence_index=evidence_index,
        )
        return res.model_dump(), ev

    async def explain_move(
        self,
        code: str,
        from_snapshot_id: int,
        to_snapshot_id: int,
        turn_id: str = "",
        evidence_index: int = 1,
    ) -> tuple[dict[str, Any], Evidence]:
        """Decompose warrant price move across underlying, time, IV, and residual."""
        from warrantx.tools.explain import execute_explain_move

        res, ev = await execute_explain_move(
            repo=self.repo,
            code=code,
            from_snapshot_id=from_snapshot_id,
            to_snapshot_id=to_snapshot_id,
            turn_id=turn_id,
            evidence_id=f"E{evidence_index}",
        )
        return res.model_dump(), ev



